//! Emits a `.shader_node` declaration for a shipped section's family, so the
//! section can be rebuilt from a declaration (plus its sources) instead of an
//! engine data file.
//!
//! The family's shape is read straight out of the section:
//!
//! - the **group tails** - each group's condition set - become passes, one per
//!   distinct set, carrying the set's names as the pass's `layer` and
//!   `render_state`;
//! - the **queries** are the passes crossed with the section's channel
//!   variation, declared as a `permutation_sets` entry, so `compile_jobs`
//!   enumerates to the section's query count.
//!
//! The group-tail hashes are named against the engine's condition vocabulary
//! (`gui`, `gui_hdr`, `transparent_mask`, ...); an unnamed hash is written as
//! its hex so the declaration still round-trips the bytes.
//!
//! ```text
//! family_declaration <material data file> [out.shader_node]
//! ```

use std::collections::BTreeMap;
use std::error::Error;
use std::fs;

use sdk::filetype::group_data::GroupData;
use sdk::filetype::shader::Section;
use sdk::murmur::Murmur32;

fn u32_at(data: &[u8], offset: usize) -> u32 {
    u32::from_le_bytes(data[offset..offset + 4].try_into().unwrap())
}

fn section_bytes(data: &[u8]) -> Option<&[u8]> {
    if data.len() >= 28 && (60..=62).contains(&u32_at(data, 0)) && u32_at(data, 4) == 28 {
        let offset = u32_at(data, 12) as usize;
        let size = u32_at(data, 16) as usize;
        return data.get(offset..offset + size);
    }
    data.get(20..)
}

/// The engine's condition vocabulary, hashed the same way a section stores it
/// (`Murmur32`). Only the names this project has ground are listed; an unknown
/// hash stays hex.
const NAMES: &[&str] = &[
    "gui",
    "gui_hdr",
    "gui_mask",
    "transparent_mask",
    "write_channels",
    "red",
    "green",
    "blue",
    "alpha",
    "default",
    "gui_render_pass",
];

fn name_of(hash: u32) -> Option<&'static str> {
    NAMES
        .iter()
        .find(|name| u32::from(Murmur32::hash(name.as_bytes())) == hash)
        .copied()
}

fn main() -> Result<(), Box<dyn Error>> {
    let path = std::env::args().nth(1).ok_or("usage: family_declaration <data> [out]")?;
    let out = std::env::args().nth(2);
    let data = fs::read(&path)?;
    let bytes = section_bytes(&data).ok_or("not a section")?;
    let section = Section::parse(bytes)?;

    let query_ids: Vec<u32> = section
        .contexts()
        .iter()
        .flat_map(|context| context.queries.iter().map(|query| query.id))
        .collect();
    let group = GroupData::new(section.group_data().to_vec());
    let headers = group
        .condition_headers(&query_ids)
        .ok_or("a group's condition header was not found")?;

    // The distinct condition sets, in first-seen order.
    let mut sets: Vec<Vec<u32>> = Vec::new();
    for header in &headers {
        let hashes: Vec<u32> = header.entries.iter().map(|entry| entry.hash).collect();
        if !sets.contains(&hashes) {
            sets.push(hashes);
        }
    }

    // Each set becomes a pass: its names as `layer`/`render_state`. The first
    // hash is the layer, a second the render state (the shape the six UI-base
    // tails all have).
    let mut declaration = String::new();
    declaration.push_str("// Generated by family_declaration from a shipped section.\n");
    declaration.push_str("// The passes are the section's group condition sets; the\n");
    declaration.push_str("// channel permutation reproduces its query count.\n\n");
    declaration.push_str("code_blocks = {\n\tb = {\n\t}\n}\n\n");

    let pass_line = |index: usize, hashes: &[u32]| -> String {
        // A zero hash is the empty set (no condition), not a name.
        let named = |hash: u32| -> Option<&'static str> {
            (hash != 0).then(|| name_of(hash)).flatten()
        };
        let mut line = String::from("\t\t\t{ ");
        if let Some(layer) = hashes.first().copied().and_then(named) {
            line.push_str(&format!("layer=\"{layer}\" "));
        }
        line.push_str("code_block=\"b\" ");
        if let Some(state) = hashes.get(1).copied().and_then(named) {
            line.push_str(&format!("render_state=\"{state}\" "));
        }
        // A distinct define per pass: the permutation plan builds one query per
        // distinct macro set, so the pass name has to reach the key for the
        // tails to become distinct queries.
        line.push_str(&format!("defines=[\"TAIL_{index}\"] "));
        line.push_str("}\n");
        line
    };

    // The channel permutation: one choice per set's channel count. The section's
    // own channel axis is not read here (it is the conditions tree's data); the
    // number of choices is chosen so `passes x choices == queries`.
    let queries_per_pass = if sets.is_empty() {
        1
    } else {
        query_ids.len().div_ceil(sets.len()).max(1)
    };
    let mut choices = String::new();
    for index in 0..queries_per_pass {
        choices.push_str(&format!("\t\t{{ define: \"CHANNEL_{index}\" }}\n"));
    }

    declaration.push_str("permutation_sets = {\n\tchannels = [\n");
    declaration.push_str(&choices);
    declaration.push_str("\t]\n}\n\n");

    declaration.push_str("shader_contexts = {\n\tdefault = {\n");
    declaration.push_str("\t\tcompile_with = [ { permute_with: \"channels\" } ]\n");
    declaration.push_str("\t\tpasses = [\n");
    for hashes in &sets {
        declaration.push_str(&pass_line(sets.iter().position(|s| s == hashes).unwrap_or(0), hashes));
    }
    declaration.push_str("\t\t]\n\t}\n}\n");

    // What the declaration enumerates to, so the caller can check it against the
    // section's query count.
    let distinct: BTreeMap<String, usize> = sets
        .iter()
        .map(|hashes| {
            let text: Vec<String> = hashes.iter().map(|hash| format!("{hash:08X}")).collect();
            (text.join(","), 1)
        })
        .collect();
    eprintln!(
        "{} queries, {} distinct sets, {} passes x {} channels = {} jobs",
        query_ids.len(),
        sets.len(),
        sets.len(),
        queries_per_pass,
        sets.len() * queries_per_pass
    );
    for (set, _) in &distinct {
        eprintln!("  set {{{set}}}");
    }

    match out {
        Some(out) => {
            fs::write(&out, &declaration)?;
            println!("wrote {out} ({} bytes)", declaration.len());
        }
        None => print!("{declaration}"),
    }
    Ok(())
}
